public static String getMessageForDay(int dayOfYear) {
    if (dayOfYear < 1 || dayOfYear > 366) {
        throw new IllegalArgumentException(
                "Day of year must be between 1 and 366."
        );
    }

    return MESSAGES[(dayOfYear - 1) % MESSAGES.length];
}

